export function getItemById(id?: string): AvatarItem | undefined {
  if (!id) return undefined;
  const legacy = AVATAR_ITEMS.find((item) => item.id === id);
  if (legacy) return legacy;
  const shopItem = getShopItemById(id);
  if (shopItem) {
    const slotMap: Record<string, "head" | "body" | "hand" | "aura"> = {
      HEAD: "head",
      CHEST: "body",
      LEGS: "body",
      MAIN_HAND: "hand",
      OFF_HAND: "hand",
      BACK: "body",
      ACCESSORY: "aura",
      HEAD_UPPER: "head",
      HEAD_MIDDLE: "head",
      HEAD_LOWER: "head",
      ARMOR: "body",
      GARMENT: "body",
      FOOTGEAR: "body",
      RIGHT_HAND: "hand",
      LEFT_HAND: "hand",
      BACKPACK: "body",
      PET_FAMILIAR: "aura",
    };
    return {
      id: shopItem.id,
      name: shopItem.name,
      slot: slotMap[shopItem.slot] || "body",
      archetype: "all",
      description: shopItem.description,
      price: shopItem.costCoins,
      minLevel: shopItem.requiredLevel,
      rarity: shopItem.rarity.toLowerCase() as any,
      inspiration: shopItem.inspiration,
      statBonus: shopItem.statBonus,
    };
  }
  return undefined;
}

export function getItemsBySlot(slot: string): AvatarItem[] {
  return AVATAR_ITEMS.filter((item) => item.slot === slot);
}

export function getItemsForArchetype(archetype: string): AvatarItem[] {
  return AVATAR_ITEMS.filter(
    (item) => item.archetype === "all" || item.archetype === archetype
  );
}
